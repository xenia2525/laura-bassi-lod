/* Laura Bassi in Linked Open Data – page behaviour.
   All data comes from assets/site-data.js, generated by scripts/build_site.py. */
(function () {
  const S = window.SITE;
  if (!S) return;
  const SVGNS = "http://www.w3.org/2000/svg";
  const TYPE_NAMES = { person: "person", place: "place", org: "organisation", event: "event", work: "work", concept: "concept" };
  const nodesById = Object.fromEntries(S.graph.nodes.map(n => [n.id, n]));
  const esc = s => String(s).replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");

  /* ------------------------------------------------------------ orrery */
  function orrery() {
    const svg = document.getElementById("orrery");
    const el = (name, attrs, parent) => {
      const e = document.createElementNS(SVGNS, name);
      for (const k in attrs) e.setAttribute(k, attrs[k]);
      (parent || svg).appendChild(e);
      return e;
    };
    const RINGS = [
      { r: 120, types: ["event"] },
      { r: 225, types: ["place", "org"] },
      { r: 330, types: ["person", "work", "concept"] },
    ];
    const pos = { laura_bassi: { x: 0, y: 0, a: 0, ring: -1 } };

    RINGS.forEach((ring, i) => {
      let members = S.graph.nodes.filter(n => ring.types.includes(n.type) && n.id !== "laura_bassi");
      if (ring.types[0] === "event") {
        const order = Object.fromEntries(S.events.map((e, k) => [e.id, k]));
        members.sort((a, b) => order[a.id] - order[b.id]);
      } else {
        members.sort((a, b) => ring.types.indexOf(a.type) - ring.types.indexOf(b.type) || a.label.localeCompare(b.label));
      }
      const offset = i * 0.21;
      members.forEach((n, k) => {
        const a = offset + (k / members.length) * Math.PI * 2;
        pos[n.id] = { x: ring.r * Math.sin(a), y: -ring.r * Math.cos(a), a, ring: i };
      });
      el("circle", { class: "orbit", r: ring.r });
    });

    // an engraved scale around the outer orbit
    const ticks = el("g", { "aria-hidden": "true" });
    for (let d = 0; d < 360; d += 3) {
      const a = d * Math.PI / 180, long = d % 30 === 0;
      const r1 = 372, r2 = long ? 384 : 378;
      el("line", { class: "tick", x1: r1 * Math.sin(a), y1: -r1 * Math.cos(a), x2: r2 * Math.sin(a), y2: -r2 * Math.cos(a) }, ticks);
    }

    const edgeLayer = el("g", { "aria-hidden": "true" });
    const edgeEls = S.graph.edges.filter(e => pos[e.s] && pos[e.t]).map(e => {
      const p = pos[e.s], q = pos[e.t];
      const mx = (p.x + q.x) / 2, my = (p.y + q.y) / 2;
      const pull = (p.ring === -1 || q.ring === -1) ? 1 : 0.55;
      const path = el("path", { class: "edge", d: `M${p.x},${p.y} Q${mx * pull},${my * pull} ${q.x},${q.y}` }, edgeLayer);
      return { e, path };
    });

    const nodeLayer = el("g", {});
    const nodeEls = {};
    S.graph.nodes.forEach(n => {
      if (n.id === "laura_bassi" || !pos[n.id]) return;
      const p = pos[n.id];
      const g = el("g", { class: `node k-${n.type}`, tabindex: 0, role: "button", "aria-label": `${n.label}, ${TYPE_NAMES[n.type]}` }, nodeLayer);
      el("circle", { cx: p.x, cy: p.y, r: p.ring === 0 ? 9 : 7 }, g);
      if (p.ring === 2) {
        const deg = p.a * 180 / Math.PI;
        const left = deg > 180;
        const lx = (330 + 14) * Math.sin(p.a), ly = -(330 + 14) * Math.cos(p.a);
        const t = el("text", {
          x: lx, y: ly, dy: "0.35em",
          transform: `rotate(${left ? deg + 90 : deg - 90} ${lx} ${ly})`,
          "text-anchor": left ? "end" : "start",
        }, g);
        t.textContent = n.label.length > 30 ? n.label.slice(0, 29) + "…" : n.label;
      }
      nodeEls[n.id] = g;
    });

    const sun = el("g", { class: "node sun", tabindex: 0, role: "button", "aria-label": "Laura Bassi, person" });
    el("circle", { class: "halo", r: 62 }, sun);
    el("circle", { r: 50 }, sun);
    const st = el("text", { y: 10 }, sun);
    st.textContent = "Bassi";
    nodeEls.laura_bassi = sun;

    const info = document.getElementById("orrery-info");
    const defaultInfo = info.innerHTML;
    let pinned = null;

    function show(id) {
      const n = nodesById[id];
      const rels = edgeEls.filter(({ e }) => e.s === id || e.t === id);
      const linked = new Set([id]);
      edgeEls.forEach(({ e, path }) => {
        const on = e.s === id || e.t === id;
        path.classList.toggle("on", on);
        if (on) { linked.add(e.s); linked.add(e.t); }
      });
      for (const k in nodeEls) {
        nodeEls[k].classList.toggle("dim", !linked.has(k));
        nodeEls[k].classList.toggle("on", k === id);
      }
      const items = rels.map(({ e }) => e.s === id
        ? `<li><code>${esc(e.p)}</code> ${esc(nodesById[e.t].label)}</li>`
        : `<li>${esc(nodesById[e.s].label)} <code>${esc(e.p)}</code></li>`).join("");
      info.innerHTML = `<strong>${esc(n.label)}</strong>
        <p>${TYPE_NAMES[n.type]}${n.wikidata ? ` · <a href="${n.wikidata}">Wikidata</a>` : ""}</p>
        ${items ? `<ul>${items}</ul>` : "<p>No direct relations in the dataset.</p>"}`;
    }
    function reset() {
      if (pinned) return show(pinned);
      edgeEls.forEach(({ path }) => path.classList.remove("on"));
      for (const k in nodeEls) nodeEls[k].classList.remove("dim", "on");
      info.innerHTML = defaultInfo;
    }
    for (const id in nodeEls) {
      const g = nodeEls[id];
      g.addEventListener("mouseenter", () => show(id));
      g.addEventListener("focus", () => show(id));
      g.addEventListener("mouseleave", reset);
      g.addEventListener("blur", reset);
      const toggle = () => { pinned = pinned === id ? null : id; pinned ? show(id) : reset(); };
      g.addEventListener("click", toggle);
      g.addEventListener("keydown", ev => {
        if (ev.key === "Enter" || ev.key === " ") { ev.preventDefault(); toggle(); }
        if (ev.key === "Escape") { pinned = null; reset(); }
      });
    }
  }

  /* ------------------------------------------------------------ numbers */
  function readout() {
    const s = S.stats, f = n => n.toLocaleString("en");
    const rows = [
      [f(s.words), "words of text encoded"],
      [s.annotations, "annotations in the text"],
      [s.entities, "entities described"],
      [s.wikidata, "matched to Wikidata"],
      [s.relations, "relations encoded"],
      [s.triples, "RDF triples"],
    ];
    document.getElementById("readout").innerHTML =
      rows.map(([v, l]) => `<div><dd>${v}</dd><dt>${l}</dt></div>`).join("");
  }

  /* ------------------------------------------------------------ entity browser */
  function entities() {
    const list = document.getElementById("entity-list");
    const chips = document.getElementById("chips");
    const order = ["person", "place", "org", "event", "work", "concept"];
    const nodes = S.graph.nodes.slice().sort((a, b) => order.indexOf(a.type) - order.indexOf(b.type) || a.label.localeCompare(b.label));
    const render = type => {
      list.innerHTML = nodes.filter(n => !type || n.type === type).map(n =>
        `<li class="k-${n.type}"><span><i></i>${esc(n.label)}</span>${n.wikidata ? `<a href="${n.wikidata}">${n.wikidata.split("/").pop()}</a>` : ""}</li>`).join("");
    };
    const types = [null, ...order];
    chips.innerHTML = types.map(t => {
      const count = t ? nodes.filter(n => n.type === t).length : nodes.length;
      return `<button type="button" class="${t ? "k-" + t : ""}" data-type="${t || ""}" aria-pressed="${t ? "false" : "true"}">${t ? "<i></i>" : ""}${t ? TYPE_NAMES[t] : "all"} (${count})</button>`;
    }).join("");
    chips.addEventListener("click", ev => {
      const b = ev.target.closest("button");
      if (!b) return;
      chips.querySelectorAll("button").forEach(x => x.setAttribute("aria-pressed", String(x === b)));
      render(b.dataset.type || null);
    });
    render(null);
  }

  /* ------------------------------------------------------------ code */
  function highlight(code, lang) {
    let h = esc(code);
    if (lang === "xml") {
      return h.replace(/(&lt;!--[\s\S]*?--&gt;)|(&lt;\/?[\w:.-]+)|([\w:.-]+)=("[^"]*")|(\/?&gt;)/g, (m, com, tag, attr, val, close) =>
        com ? `<span class="t-com">${com}</span>` :
        tag ? `<span class="t-tag">${tag}</span>` :
        attr ? `<span class="t-attr">${attr}</span>=<span class="t-str">${val}</span>` :
        `<span class="t-tag">${close}</span>`);
    }
    const kw = lang === "python" ? "for|in|if|else|elif|not|return|def|import|from" : "a";
    return h.replace(new RegExp(`(&lt;[^\\s&]*&gt;)|(#[^\\n]*)|("(?:[^"\\\\]|\\\\.)*")|\\b(${kw})\\b`, "g"), (m, uri, com, str, k) =>
      uri ? `<span class="t-attr">${uri}</span>` :
      com ? `<span class="t-com">${com}</span>` :
      str ? `<span class="t-str">${str}</span>` :
      `<span class="t-kw">${k}</span>`);
  }
  function tabs() {
    document.querySelectorAll("[data-tabs]").forEach(box => {
      const code = box.querySelector("pre code");
      const buttons = box.querySelectorAll("[role=tab]");
      const select = b => {
        buttons.forEach(x => x.setAttribute("aria-selected", String(x === b)));
        let text = S.snippets[b.dataset.snippet] || "";
        code.innerHTML = highlight(text, b.dataset.lang);
      };
      buttons.forEach(b => b.addEventListener("click", () => select(b)));
      select(buttons[0]);
    });
  }

  /* ------------------------------------------------------------ timeline */
  function timeline() {
    const months = ["January", "February", "March", "April", "May", "June", "July", "August", "September", "October", "November", "December"];
    document.getElementById("timeline").innerHTML = S.events.map(e => {
      const [y, m, d] = e.date.split("-");
      const sub = m ? `${d ? +d + " " : ""}${months[+m - 1]}` : "";
      const meta = [e.place, e.by].filter(Boolean).join(", ");
      return `<li><time datetime="${e.date}">${y}${sub ? `<small>${sub}</small>` : ""}</time><div><b>${esc(e.label)}</b><span>${esc(meta)}</span></div></li>`;
    }).join("");
  }

  /* ------------------------------------------------------------ rail */
  function rail() {
    const links = [...document.querySelectorAll(".rail a")];
    if (!("IntersectionObserver" in window)) return;
    const io = new IntersectionObserver(entries => {
      entries.forEach(en => {
        if (en.isIntersecting) links.forEach(a => a.classList.toggle("current", a.getAttribute("href") === "#" + en.target.id));
      });
    }, { rootMargin: "-40% 0px -55% 0px" });
    document.querySelectorAll(".step").forEach(s => io.observe(s));
  }

  orrery(); readout(); entities(); tabs(); timeline(); rail();
})();
